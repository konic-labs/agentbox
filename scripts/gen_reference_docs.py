"""Regenerate the reference docs from the code.

    python scripts/gen_reference_docs.py          # write docs/{cli,config}-reference.md
    python scripts/gen_reference_docs.py --check  # exit 1 if either is out of date (CI)

The CLI reference comes from the Typer app (hidden deprecated aliases left out);
the configuration reference from the pydantic models' fields, defaults and
descriptions.
"""

from __future__ import annotations

import re
import subprocess
import sys
import types
import typing
from pathlib import Path
from typing import Any

import typer
from pydantic import BaseModel
from pydantic_core import PydanticUndefined

from agentbox.cli.main import app

DOCS = Path(__file__).resolve().parents[1] / "docs"
HEADER = "<!-- Generated by scripts/gen_reference_docs.py; do not edit by hand. -->\n\n"


# --------------------------------------------------------------------- CLI
def hidden_commands() -> set[str]:
    group = typer.main.get_command(app)
    return {name for name, cmd in getattr(group, "commands", {}).items() if cmd.hidden}


def render_cli() -> str:
    raw = subprocess.run(
        ["typer", "agentbox.cli.main", "utils", "docs", "--name", "agentbox"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    hidden = hidden_commands()
    out: list[str] = []
    skipping = False
    in_root = True  # the root command list is the only one naming hidden commands
    for line in raw.splitlines():
        heading = re.match(r"^#+ `agentbox ([^`\s]+)", line)
        if heading:
            in_root = False
            skipping = heading.group(1) in hidden
        if skipping:
            continue
        item = re.match(r"^\* `([^`]+)`: ", line)
        if in_root and item and item.group(1) in hidden:
            continue
        out.append(line)
    return HEADER + "\n".join(out).strip() + "\n"


# ------------------------------------------------------------------ config
def _type_name(tp: Any) -> str:
    origin = typing.get_origin(tp)
    if origin in (typing.Union, types.UnionType):
        return " \\| ".join(_type_name(a) for a in typing.get_args(tp))
    if origin is typing.Literal:
        return " \\| ".join(repr(a) for a in typing.get_args(tp))
    if origin is not None:
        args = ", ".join(_type_name(a) for a in typing.get_args(tp))
        return f"{getattr(origin, '__name__', str(origin))}[{args}]"
    if tp is type(None):
        return "None"
    return getattr(tp, "__name__", str(tp).replace("typing.", ""))


def _default(field: Any) -> str:
    if field.default_factory is not None:
        try:
            value = field.default_factory()
        except TypeError:
            return "*(factory)*"
    elif field.default is PydanticUndefined:
        return "**required**"
    else:
        value = field.default
    if isinstance(value, BaseModel):
        return f"`{type(value).__name__}()`"
    if hasattr(value, "value"):  # enums
        value = value.value
    text = repr(value)
    return f"`{text}`" if len(text) <= 48 else f"`{text[:45]}...`"


def _model_table(model: type[BaseModel]) -> list[str]:
    doc = (model.__doc__ or "").strip().split("\n\n")[0].replace("\n", " ")
    rows = [f"### `{model.__name__}`", "", doc, "", "| field | type | default | description |"]
    rows.append("| --- | --- | --- | --- |")
    for name, field in model.model_fields.items():
        desc = (field.description or "").replace("|", "\\|").replace("\n", " ")
        rows.append(f"| `{name}` | {_type_name(field.annotation)} | {_default(field)} | {desc} |")
    return [*rows, ""]


def render_config() -> str:
    from agentbox.config import (
        AgentConfig,
        ModelConfig,
        ResourceLimits,
        RolloutConfig,
        SandboxConfig,
        SecurityConfig,
    )
    from agentbox.config_load import ProjectConfig
    from agentbox.rewards import RewardSpec
    from agentbox.tasks.schema import EnvironmentSpec, Task, VerifierSpec

    sections: list[tuple[str, str, list[type[BaseModel]]]] = [
        (
            "Project file (`agentbox.yaml`)",
            "Loaded by every CLI command (`--config`, `$AGENTBOX_CONFIG`, or "
            "`./agentbox.yaml`); see [configuration.md](configuration.md).",
            [ProjectConfig],
        ),
        (
            "Runtime configuration",
            "Python objects behind the project file sections; also accepted directly "
            "by `Rollout`, `ParallelRunner`, `AgentBoxEnv` and the trainer integrations.",
            [
                SandboxConfig,
                ResourceLimits,
                SecurityConfig,
                ModelConfig,
                AgentConfig,
                RolloutConfig,
                RewardSpec,
            ],
        ),
        (
            "Task schema",
            "`task.json` files, JSONL/Parquet rows and `Task(...)` objects; see "
            "[tasks.md](tasks.md).",
            [Task, VerifierSpec, EnvironmentSpec],
        ),
    ]
    lines = [HEADER.rstrip(), "", "# Configuration reference", ""]
    for title, intro, models in sections:
        lines += [f"## {title}", "", intro, ""]
        for model in models:
            lines += _model_table(model)
    return "\n".join(lines).rstrip() + "\n"


# -------------------------------------------------------------------- main
def main() -> int:
    outputs = {
        DOCS / "cli-reference.md": render_cli(),
        DOCS / "config-reference.md": render_config(),
    }
    if "--check" in sys.argv:
        stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        for p in stale:
            print(f"{p} is out of date: run python scripts/gen_reference_docs.py")
        return 1 if stale else 0
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
