@train_app.command("trl")
def train_trl(
    ctx: typer.Context,
    tasks: Annotated[list[Path], typer.Argument(help="Training tasks")],
    model: Annotated[str, typer.Option("--model", "-m")] = "Qwen/Qwen3-0.6B",
    out: Annotated[Path, typer.Option("--out", "-o")] = Path("grpo-agentbox"),
    steps: Annotated[int, typer.Option("--steps")] = 100,
    group_size: Annotated[int, typer.Option("--group-size", help="num_generations")] = 8,
    batch_size: Annotated[int | None, typer.Option("--batch-size")] = None,
    lr: Annotated[float, typer.Option("--lr")] = 1e-6,
    max_completion_length: Annotated[int, typer.Option("--max-completion-length")] = 1024,
    max_tool_calls: Annotated[int, typer.Option("--max-tool-calls")] = 8,
    tools: Annotated[str, typer.Option("--tools", help="Comma-separated tool names")] = (
        "list_files,read_file,write_file,run_tests"
    ),
    use_vllm: Annotated[bool, typer.Option("--use-vllm/--no-vllm")] = False,
    thinking: Annotated[bool, typer.Option("--thinking/--no-thinking")] = False,
    peft: Annotated[bool, typer.Option("--lora/--no-lora", help="Train a LoRA adapter")] = False,
) -> None:
    """GRPO via TRL with AgentBox sandboxes as the environment."""
    try:
        from trl import GRPOConfig, GRPOTrainer
    except ImportError:
        fail("TRL is not installed: pip install 'agentbox-rl[trl]'")
    from agentbox.config import AgentConfig, SandboxConfig
    from agentbox.integrations.trl import make_environment_factory, tasks_to_dataset
    from agentbox.tasks.loader import iter_tasks

    st = state(ctx)
    task_list = list(iter_tasks(tasks))
    if not task_list:
        fail("no tasks found")
    agent = st.project.agent or AgentConfig()
    env_cls = make_environment_factory(
        task_list,
        sandbox=st.project.sandbox or SandboxConfig(),
        agent=agent,
        rewards=st.project.rewards,
        tools=[t.strip() for t in tools.split(",") if t.strip()],
    )
    kwargs: dict[str, object] = {}
    if peft:
        try:
            from peft import LoraConfig
        except ImportError:
            fail("--lora needs: pip install peft")
        kwargs["peft_config"] = LoraConfig(r=16, lora_alpha=32, target_modules="all-linear")
    trainer = GRPOTrainer(
        model=model,
        train_dataset=tasks_to_dataset(task_list, agent=agent),
        environment_factory=env_cls,
        args=GRPOConfig(
            output_dir=str(out),
            max_steps=steps,
            num_generations=group_size,
            per_device_train_batch_size=batch_size or group_size,
            learning_rate=lr,
            max_completion_length=max_completion_length,
            max_tool_calling_iterations=max_tool_calls,
            use_vllm=use_vllm,
            chat_template_kwargs={"enable_thinking": thinking},
            logging_steps=1,
            bf16=True,
            report_to="none",
        ),
        **kwargs,
    )
    trainer.train()
    trainer.save_model(str(out))
    emit(st, {"out": str(out), "steps": steps}, lambda: typer.echo(f"saved {out}"))
